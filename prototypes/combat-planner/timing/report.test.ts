import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

import type { CellRow } from './cell';

/** Tables for RESULTS.md from `out/*.json` (written to `out/tables.md`). */

type Row = CellRow & Record<string, unknown>;

const read = (name: string): Row[] => {
  const url = new URL(`./out/${name}.json`, import.meta.url);
  return existsSync(url) ? (JSON.parse(readFileSync(url, 'utf8')) as Row[]) : [];
};

const f = (x: number, d = 0) => (Number.isFinite(x) ? x.toFixed(d) : '—');
const sum = (rows: readonly Row[], k: keyof CellRow) =>
  rows.reduce((t, r) => t + (r[k] as number), 0);
const wmean = (rows: readonly Row[], k: keyof CellRow, w: (r: Row) => number) =>
  rows.reduce((t, r) => t + (r[k] as number) * w(r), 0) /
  Math.max(
    1e-9,
    rows.reduce((t, r) => t + w(r), 0),
  );
const byFights = (r: Row) => r.fights;
const byRounds = (r: Row) => r.fights * r.rounds;

function table(head: readonly string[], body: readonly (readonly string[])[]): string {
  return [
    `| ${head.join(' | ')} |`,
    `| ${head.map(() => '---').join(' | ')} |`,
    ...body.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');
}

function group<T>(xs: readonly T[], key: (x: T) => string): Map<string, T[]> {
  const m = new Map<string, T[]>();
  for (const x of xs) m.set(key(x), [...(m.get(key(x)) ?? []), x]);
  return m;
}

const invalidPerRound = (rows: readonly Row[]) => {
  const all: Record<string, number> = {};
  for (const r of rows) for (const [k, v] of Object.entries(r.invalid)) all[k] = (all[k] ?? 0) + v;
  const rounds = rows.reduce((t, r) => t + byRounds(r), 0);
  return (
    Object.entries(all)
      .map(([k, v]) => `${k} ${f(v / rounds, 2)}`)
      .join(', ') || '—'
  );
};

const combos = (rows: readonly Row[]) => {
  const all: Record<string, number> = {};
  for (const r of rows) for (const [k, v] of Object.entries(r.combos)) all[k] = (all[k] ?? 0) + v;
  return (
    Object.entries(all)
      .map(([k, v]) => `${k} ×${v}`)
      .join(', ') || '—'
  );
};

function policyTable(rows: readonly Row[], title: string): string {
  const out: string[] = [`### ${title}`, ''];
  const body: string[][] = [];
  for (const [policy, rs] of group(rows, (r) => r.policy as string)) {
    const audits = rs.reduce((t, r) => t + r.audits, 0);
    body.push([
      policy,
      `${sum(rs, 'won')}/${sum(rs, 'fights')}`,
      f(wmean(rs, 'dealt', byFights)),
      f(wmean(rs, 'taken', byFights)),
      f(wmean(rs, 'msPerRound', byRounds)),
      f(Math.max(...rs.map((r) => r.msPerRoundP95))),
      `${f(wmean(rs, 'plansPerRound', byRounds), 2)}${rs[0]!.lightPerRound ? ` + ${f(wmean(rs, 'lightPerRound', byRounds), 2)} light` : ''}`,
      f(wmean(rs, 'exchangesSimPerRound', byRounds)),
      invalidPerRound(rs),
      audits
        ? `${audits}: ${f(100 * wmean(rs, 'agreed', (r) => r.audits))}%, ${f(
            wmean(rs, 'regretMean', (r) => r.audits),
            1,
          )}`
        : '—',
      combos(rs),
    ]);
  }
  out.push(
    table(
      [
        'policy',
        'won',
        'dealt',
        'taken',
        'ms / round',
        'p95 (worst cell)',
        'plans / round',
        'sim exchanges / round',
        'invalidations / round',
        'audits: agree, regret',
        'combos played',
      ],
      body,
    ),
  );
  return out.join('\n');
}

it('writes the tables', () => {
  const parts: string[] = ['# Tables (generated by report.test.ts)', ''];
  const light = (rs: Row[]) => rs.filter((r) => r.policy !== 'round + reactive (replan)');
  const q1s = [...read('q1-scenarios-all'), ...read('q1-scenarios-light')];
  const q1p = [
    ...read('q1-pairs-all').filter((r) => r.policy !== 'round + reactive (replan)'),
    ...read('q1-pairs-light'),
  ];
  void light;
  for (const [g, rs] of group(q1s, (r) => r.group as string))
    parts.push(policyTable(rs, `Q1 ${g} (30 fights, cap 8)`), '');
  if (q1p.length) parts.push(policyTable(q1p, `Q1 bench pairs (12 pairs × seeds, cap 16)`), '');
  const q2 = read('q2-all');
  if (q2.length) {
    for (const [g, rs] of group(q2, (r) =>
      String(r.group).includes('-v-') ? 'bench pairs' : String(r.group),
    )) {
      parts.push(policyTable(rs, `Q2 ${g}`), '');
    }
  }
  const q3tags = readdirSync(new URL('./out/', import.meta.url))
    .filter((n) => n.startsWith('q3-'))
    .map((n) => n.slice(3, -5))
    .sort();
  for (const tag of q3tags) {
    const rows = read(`q3-${tag}`);
    if (!rows.length) continue;
    const body: string[][] = [];
    for (const [k, rs] of group(rows, (r) => `${r.tier} as ${r.side}`)) {
      body.push([
        k,
        `${sum(rs, 'won')}/${sum(rs, 'fights')}`,
        `${sum(rs, 'lost')}`,
        f(wmean(rs, 'dealt', byFights)),
        f(wmean(rs, 'taken', byFights)),
        f(wmean(rs, 'dealt', byFights) - wmean(rs, 'taken', byFights)),
        f(wmean(rs, 'msPerRound', byRounds)),
        f(wmean(rs, 'plansPerRound', byRounds), 2),
        f(wmean(rs, 'exchangesSimPerRound', byRounds)),
        combos(rs),
      ]);
    }
    parts.push(
      `### Q3 ${tag}`,
      '',
      table(
        [
          'tier',
          'won',
          'lost',
          'dealt',
          'taken',
          'net',
          'ms / round',
          'plans / round',
          'sim ex / round',
          'combos',
        ],
        body,
      ),
      '',
    );
  }
  for (const tag of ['alone', 'alone-v3']) {
    const q4 = read(`q4-${tag}`);
    if (!q4.length) continue;
    const body = q4.map((r) => [
      `${r.lineup} ${r.size}v${r.size}`,
      String(r.grades),
      String(r.mix),
      f(r.allMsPerRound),
      f(r.allMsPerRoundP95),
      f(r.allExPerRound as number),
      f(r.allMsStartPerRound as number),
      `${f(r.allMidGapP50 as number)} / ${f(r.allMidGapP95 as number)}`,
      f(r.msPerRound),
      `${r.won}/${r.fights}`,
    ]);
    parts.push(
      `### Q4 (${tag})`,
      '',
      table(
        [
          'fight',
          'intellect grades',
          'mix',
          'all planners ms / round',
          'p95',
          'sim exchanges / round',
          'ms at round start / round',
          'ms in an exchange gap p50 / p95',
          'player ms / round',
          'won',
        ],
        body,
      ),
      '',
    );
  }
  writeFileSync(new URL('./out/tables.md', import.meta.url), parts.join('\n'));
  console.log(parts.join('\n'));
});
